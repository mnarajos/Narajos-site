function paragraph(label, text) {
  const line = document.createElement("p");
  const labelNode = document.createElement("strong");
  labelNode.textContent = label + " ";
  line.append(labelNode, text);
  return line;
}

export function homeActivity(id) {
  const [title, method, fallback, question, answer] = activities[id];
  const activity = document.createElement("details");
  activity.className = "practice-card ks3-home-activity";
  const label = document.createElement("summary");
  label.textContent = "Try at home (optional)";
  const heading = document.createElement("h2");
  heading.textContent = title;
  activity.append(label, heading, paragraph("Try it.", method));
  if (fallback) activity.append(paragraph("Just using the screen?", fallback));
  activity.append(paragraph("Think about it.", question));

  const feedback = document.createElement("details");
  const summary = document.createElement("summary");
  summary.textContent = "Check your idea";
  const model = document.createElement("p");
  model.textContent = answer;
  feedback.append(summary, model);
  activity.append(feedback);
  return activity;
}

for (const placeholder of document.querySelectorAll("[data-ks3-home]")) {
  placeholder.replaceWith(homeActivity(placeholder.dataset.ks3Home));
}
